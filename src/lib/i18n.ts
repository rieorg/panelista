export type Lang = "tl" | "en";
export type Key = keyof typeof STRINGS;

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  let s: string = STRINGS[key][lang === "tl" ? 0 : 1];
  if (typeof vars?.n === "number") vars = { s: vars.n === 1 ? "" : "s", ...vars };
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** Maps an API error code to a friendly message key. */
export function errorKey(code: string): Key {
  const k = `e_${code}`;
  return (k in STRINGS ? k : "e_generic") as Key;
}

